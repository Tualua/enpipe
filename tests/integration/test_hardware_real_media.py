"""TEST-04: hardware-gated end-to-end validation of the `enpipe` CLI
(detect -> encode -> mux) against real media on real Intel Arc QSV
hardware -- the milestone capstone. SDR and synthetic HDR10 sources are
generated in-test and genuinely encoded on this devcontainer's Arc GPU;
HDR10+/genuine Dolby Vision are fixture-gated (D-06) because dynamic
metadata / real RPU content cannot be reliably synthesized in-sandbox.

IMPORTANT (qwen H1): the SOURCE clips generated by `_make_multiscene_clip`
are produced by a SOFTWARE ffmpeg encode (libx264/libx265) -- that step
needs no GPU at all. The `hardware` marker / `_require_hardware` gate below
applies ONLY to the `enpipe` pipeline's own encode step, which drives the
real `qsvencc` QSV hardware encoder against /dev/dri/renderD128.

The devcontainer runs on Ubuntu 24.04 + the Intel PPA with intel-opencl-icd,
so qsvencc --psnr/--ssim work. test_sdr, test_hdr10 and
test_sdr_legacy_oracle_parity are parametrized over metrics (Phase 8 D-10d).
In the metrics variant the FULL stderr of every qsvencc call is captured by a
wrapper placed on PATH. An attempt is retried (up to METRICS_ATTEMPTS) only
when every failed qsvencc call failed in the metrics subsystem (D-12, known
defect, backlog) and there is no frame-count mismatch. Any other failure is an
immediate test failure. Exhausting the attempts is a failure marked
METRICS_FAILED (the metrics path is NOT verified; this is not a green). The
remaining tests deliberately keep --no-metrics: metrics are not their subject
and the metrics path is covered by the parametrized tests.

Chunk CONTENT check (`_verify_chunk_first_frames`): the first decoded frame of
every kept chunk is compared by PSNR with the SOURCE frame S that starts the
scene (decoded by the ffmpeg next to $ENPIPE_TEST_FFPROBE), plus a negative
control against source frame S+(K_next-K). It catches `qsvencc --seek` landing
one GOP late (fixed in qsvencc r4663, see
.planning/debug/HANDOFF-qsvencc-seek-firstpkt.md); that failure mode keeps frame
counts and rc intact. Open-GOP sources (leading pictures after a seek keyframe)
are not run through this check: enpipe refuses them up front because qsvencc
shifts --trim by -N on them (see
.planning/debug/HANDOFF-qsvencc-opengop-trim-offset.md);
test_open_gop_source_refused covers the refusal and
test_chunk_content_closed_gop the content check on the same layout with
open-gop=0.

DV RPU verification NEVER uses the mutating dovi_rpu ffmpeg bitstream
filter to write, and NEVER uses dovi_tool's RPU-extraction subcommand
(confirmed broken on AV1 input in the installed 2.3.2 version -- see
04-RESEARCH.md). Only a read-only `ffmpeg -h bsf=dovi_rpu` self-check
(AV1-support probe) and read-only ffprobe inspection are used: per-frame
`-show_entries frame=side_data_list` counted by "Dolby Vision Metadata", and
`-show_streams` for the "DOVI configuration record". The probing binary is
$ENPIPE_TEST_FFPROBE (default "ffprobe"); the pipeline under test always
uses the ffmpeg/ffprobe on PATH -- see the DV helpers below.

EMPIRICAL CORRECTION vs. the plan's draft interface (recorded here, not
just in the SUMMARY, so a future reader isn't misled by stale assumptions):
HDR10 mastering-display/max-CLL metadata does NOT appear at ffprobe's
STREAM level for this pipeline's mkvmerge-muxed AV1-in-.mkv output --
`ffprobe -show_streams -show_entries stream=side_data_list` returns no
side_data_list key at all (verified directly against a real produced HDR10
.mkv in this session; `mkvinfo` also confirms mkvmerge does not lift
Mastering-display/MaxCLL into a Matroska Colour element for a raw-OBU AV1
track). The metadata DOES survive, but only at the FRAME level
(`frame=side_data_list`), on every single frame -- so test_hdr10 below
checks frame-level side data for HDR10 survival, same probe entry as the
DV RPU check (Task 2) but a different side_data_type string."""

