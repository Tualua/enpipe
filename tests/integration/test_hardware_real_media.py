def _verify_ffmpeg() -> str:
    """ffmpeg sibling of VERIFY_FFPROBE (same build), else ffmpeg from PATH."""
    probe = Path(VERIFY_FFPROBE)
    if probe.parent != Path("."):
        suffix = probe.name[len("ffprobe"):] if probe.name.startswith("ffprobe") else ""
        return str(probe.parent / ("ffmpeg" + suffix))
    return "ffmpeg"


def _source_start_time(src: Path) -> float:
    """Container start_time of the source (read-only probe)."""
    out = subprocess.run(
        [VERIFY_FFPROBE, "-v", "error", "-show_entries", "format=start_time",
         "-of", "default=nw=1:nk=1", str(src)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    try:
        return float(out)
    except ValueError:
        return 0.0


def _verify_chunk_first_frames(
    src: Path, workdir: Path, scenes: List[Tuple[int, int]], tmp: Path
) -> int:
    """First frame of chunk_{i:05d}.obu vs source frame S (scene start), by
    PSNR, with a wrong-GOP negative control at S+(K_next-K). Chunks are
    numbered from 0 within `scenes`. Returns the number of chunks where the
    negative control was discriminating. Collect-then-report."""
    ffmpeg = _verify_ffmpeg()
    fps = probe_fps(src)
    table = keyframe_table_ffprobe(src, fps)  # independent ground truth
    total = count_frames(src)
    start_time = _source_start_time(src)
    kf_frames = [f for f, _ in table]
    tmp.mkdir(parents=True, exist_ok=True)

    errors: List[str] = []
    oks: List[float] = []
    disc_count = 0
    for i, (s, e) in enumerate(scenes):
        chunk = workdir / f"chunk_{i:05d}.obu"
        k, k_time = kf_before(table, s)
        later = [f for f in kf_frames if f > k]
        k_next = later[0] if later else None
        alt = s + (k_next - k) if k_next is not None else None
        if alt is not None and alt >= total:
            alt = None

        c0 = tmp / f"c{i:05d}_chunk.mkv"
        content.extract_chunk_first_frame(ffmpeg, chunk, c0)
        ref = tmp / f"c{i:05d}_src_s.mkv"
        content.extract_source_frame(ffmpeg, src, s, k, k_time, fps, start_time, ref)
        psnr_ok = content.psnr_db(ffmpeg, c0, ref)
        psnr_alt: Optional[float] = None
        psnr_src_alt: Optional[float] = None
        if alt is not None:
            # K of the alt frame, for the fast extraction path
            ka, ka_time = kf_before(table, alt)
            ref_alt = tmp / f"c{i:05d}_src_alt.mkv"
            content.extract_source_frame(
                ffmpeg, src, alt, ka, ka_time, fps, start_time, ref_alt
            )
            psnr_alt = content.psnr_db(ffmpeg, c0, ref_alt)
            psnr_src_alt = content.psnr_db(ffmpeg, ref, ref_alt)
        err, disc = content.first_frame_verdict(psnr_ok, psnr_alt, psnr_src_alt)
        oks.append(psnr_ok)
        disc_count += 1 if disc else 0
        print(
            f"[content] {src.name} chunk {i} scene [{s},{e}) K={k} K_next={k_next} "
            f"psnr_ok={psnr_ok:.2f} psnr_alt={psnr_alt} psnr_src_alt={psnr_src_alt} "
            f"discriminating={disc}"
        )
        if err is not None:
            errors.append(
                f"chunk {i} scene [{s},{e}) K={k} K_next={k_next}: {err} "
                f"(psnr_ok={psnr_ok:.2f}, psnr_alt={psnr_alt}, "
                f"psnr_src_alt={psnr_src_alt})"
            )
    print(
        f"[content] {src.name}: min psnr_ok={min(oks) if oks else None}, "
        f"discriminating chunks={disc_count}/{len(scenes)}"
    )
    assert not errors, (
        f"chunk content mismatch on {src.name} (frame counts may still match -- "
        f"suspect a qsvencc seek issue; the firstpkt seek bug is "
        f"fixed in r4663, see .planning/debug/HANDOFF-qsvencc-seek-firstpkt.md):\n" + "\n".join(errors)
    )
    return disc_count


def _av1_dovi_self_check() -> bool:
    """Read-only AV1-DOVI-parsing self-check (D-07/Assumption A2, opencode
    L2): confirms that the ffmpeg build matching the verification ffprobe
    (see _verify_ffmpeg) has a dovi_rpu bitstream filter declaring AV1
    support in its Supported-codecs line via a WORD-BOUNDARY match (not
    a bare substring, which could match spuriously). This is a READ-ONLY
    `-h` (help) invocation -- it does not filter, mutate, or process any
    media; it only inspects what that ffmpeg build claims to support, so a
    toolchain downgrade fails loud (skip with an explanation) rather than
    silently under-reporting DV frames. A missing binary counts as
    unsupported."""
    try:
        proc = subprocess.run([_verify_ffmpeg(), "-hide_banner", "-h", "bsf=dovi_rpu"],
                              capture_output=True, text=True)
    except (FileNotFoundError, PermissionError):
        return False
    return re.search(r"\bav1\b", proc.stdout + proc.stderr, re.I) is not None


def _dv_metadata_frame_count(path: Path) -> Tuple[int, int]:
    """Returns (frames_with_dv_metadata, total_frames) via the SAME read-only
    frame-level ffprobe probe as the HDR10 survival check
    (_frame_side_data_types) -- no bitstream filter, no mutation.

    Counts frames whose side_data_list contains "Dolby Vision Metadata".
    ffprobe's default AV1 decoder (libdav1d) exports the parsed RPU under
    that name, whereas the raw "Dolby Vision RPU Data" entry only exists on
    the HEVC source -- counting RPU Data would yield 0 on the AV1 output even
    when every RPU survived. "Dolby Vision Metadata" is present on both, so
    source-vs-output parity compares like with like; it also works on a raw
    .obu chunk. The native av1 decoder exports no DV side data at all, hence
    the reliance on ffprobe's default decoder (libdav1d)."""
    per_frame_types = _frame_side_data_types(path)
    with_md = sum(1 for types in per_frame_types if "Dolby Vision Metadata" in types)
    return with_md, len(per_frame_types)


def _dovi_config_record(path: Path) -> Optional[Dict[str, Any]]:
    """First "DOVI configuration record" side-data entry of the first video
    stream, or None. Full -show_streams is required:
    `-show_entries stream=side_data_list` returns empty dicts."""
    cmd = [VERIFY_FFPROBE, "-v", "error", "-select_streams", "v:0",
           "-show_streams", "-of", "json", str(path)]
    data = json.loads(subprocess.run(cmd, capture_output=True, text=True, check=True).stdout)
    streams = data.get("streams", [])
    if not streams:
        return None
    for sd in streams[0].get("side_data_list", []):
        if sd.get("side_data_type") == "DOVI configuration record":
            return sd
    return None


